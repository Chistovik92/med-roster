# -*- coding: utf-8 -*-
"""
Классификация должностей: строка «Должность/ставка» (колонка c1 файла) →
недельная норма (30/33/36/39/40 ч) и доля ставки (1.0 / 0.75 / 0.5 / 0.25).

Правила определения недельной нормы — ЭВРИСТИЧЕСКИЕ (по подстрокам должности).
Они собраны из реальных должностей файлов «ноябрь 2026» и нормативной базы
(ст. 350 ТК РФ). Порядок проверки важен: сначала уточняющие категории
(вредный/инфекционный профиль, КДЛ), затем средний медперсонал, затем врачи.

При неоднозначности функция возвращает ``week_norm=None`` и помечает запись для
ручной сверки — конфликт-чекер покажет её как «неизвестная должность».
"""
from __future__ import annotations

import re
from typing import Optional, Tuple

# --------------------------------------------------------------------------- #
#  Определение недельной нормы по подстрокам (порядок = приоритет).
# --------------------------------------------------------------------------- #
_NORM_RULES: Tuple[Tuple[int, Tuple[str, ...]], ...] = (
    (30, ("рентген", "радиол", "лучев")),
    (36, ("лаборант", "лаб", "ифекц", "инфекц", "кдл")),
    (39, ("м/с", "м.с", "медсестр", "сестр", "фельд", "акушер",
          "м/с", "м с", "м/ с")),
    (39, ("пед", "оомпд")),
    (33, ("зубн", "офтальм", "офт", "эндокр", "неврол", "кардиол",
          "оторинол", "уролог", "андр", "хир", "травм", "гин", "узи",
          "лфк", "дн.стац", "ф.д.", "фун.д.", "нефрол")),
    (33, ("врач", "вр")),
    (40, ("регистр", "опер", "оператор", "уб.", "уб ", "уборщ",
          "гардероб", "админ", "ауп")),
    (39, ("зав", "завед", "старш")),
)

# --------------------------------------------------------------------------- #
#  Извлечение доли ставки из строки («0,5 ед», «0.75 ед», «025 ед», «0.5ед.»).
# --------------------------------------------------------------------------- #
_RATE_TOKEN_RE = re.compile(r"(\d{1,2}[.,]?\d{1,2})\s*ед", re.IGNORECASE)


def parse_rate(title: str) -> float:
    """Доля ставки из строки должности. Возвращает 1.0, если ставка не указана.

    Обрабатывает формы: ``0,5 ед``, ``0.5 ед``, ``0.75 ед``, ``0,25 ед``,
    ``0.25 ед``, опечатку ``025 ед`` (пропущена запятая → 0,25) и ``0.5ед.``
    (без пробела).
    """
    t = (title or "").strip()
    m = _RATE_TOKEN_RE.search(t)
    if not m:
        return 1.0
    token = m.group(1).replace(",", ".")
    if "." in token:
        return float(token)
    # без разделителя: «05» → 0,5; «025» → 0,25; «075» → 0,75
    if token.startswith("0") and len(token) >= 2:
        return int(token) / (10.0 ** (len(token) - 1))
    return float(token)


def _norm(s: str) -> str:
    """Нормализовать строку для поиска подстрок."""
    s = s.lower().replace("ё", "е")
    s = re.sub(r"\s+", " ", s)
    return s


def classify(title: str) -> Tuple[Optional[int], float]:
    """Определить (недельная_норма, ставка) по строке должности.

    Возвращает ``(week_norm, rate)``. ``week_norm`` может быть ``None``, если
    должность не удалось классифицировать (нужна ручная сверка).
    """
    rate = parse_rate(title)
    s = _norm(title)
    for norm, keys in _NORM_RULES:
        for k in keys:
            if k in s:
                return norm, rate
    return None, rate


def classify_with_rule(title: str) -> Tuple[Optional[int], float, Optional[str]]:
    """Как :func:`classify`, но дополнительно возвращает сработавшее правило."""
    rate = parse_rate(title)
    s = _norm(title)
    for norm, keys in _NORM_RULES:
        for k in keys:
            if k in s:
                return norm, rate, "%d ч (ключ %r)" % (norm, k)
    return None, rate, None
