LOCAL = ("127.0.0.1", 50000)


@pytest.fixture(autouse=True)
def _isolated(monkeypatch, tmp_path):
    monkeypatch.setenv("MEDROSTER_DATA_DIR", str(tmp_path))
    api_auth.reset_cache()
    main._sessions.clear()
    monkeypatch.setattr(config, "RATE_LIMIT_PER_MIN", 10000)
    monkeypatch.setattr(config, "HEAVY_RATE_LIMIT_PER_MIN", 10000)
    yield
    api_auth.reset_cache()
    main._sessions.clear()


def _client():
    return TestClient(main.app, client=LOCAL)


def _session(client):
    resp = client.post("/api/v1/roster", json={
        "year": 2026, "month": 11, "department": "УПО",
        "employees": [
            {"name": "Иванова И.И.", "position": "Вр. педиатр участковый",
             "days": {"2": "8-15,48"}},
        ]})
    assert resp.status_code == 200
    return resp.json()["session_id"]


# --------------------------------------------------------------------------- #
#  Модуль signing
# --------------------------------------------------------------------------- #
def test_sign_and_verify_roundtrip():
    data = "график ноября".encode("utf-8")
    sig = signing.sign_bytes(data)
    assert len(sig["sha256"]) == 64
    assert len(sig["hmac_sha256"]) == 64
    assert sig["sha256"] != sig["hmac_sha256"]

    assert signing.verify_bytes(data, sig["hmac_sha256"]) is True
    # изменённые данные не проходят
    assert signing.verify_bytes("график декабря".encode("utf-8"),
                                sig["hmac_sha256"]) is False
    # чужая подпись не проходит
    assert signing.verify_bytes(data, "0" * 64) is False
    assert signing.verify_bytes(data, "") is False


def test_sign_secret_env_override(monkeypatch):
    monkeypatch.setattr(config, "SIGN_SECRET", "super-secret")
    assert signing.get_sign_secret() == "super-secret"
    sig = signing.sign_bytes(b"data", secret="explicit")
    assert signing.verify_bytes(b"data", sig["hmac_sha256"],
                                secret="explicit") is True
    assert signing.verify_bytes(b"data", sig["hmac_sha256"],
                                secret="other") is False


def test_sign_secret_autogenerated_and_stable():
    """Без env секрет генерируется один раз и сохраняется в БД."""
    secret1 = signing.get_sign_secret()
    assert len(secret1) == 64
    secret2 = signing.get_sign_secret()
    assert secret1 == secret2            # стабилен между вызовами


# --------------------------------------------------------------------------- #
#  Подписанный ZIP-пакет
# --------------------------------------------------------------------------- #
def _signed_zip(client, sid, signer="Зав. УПО"):
    resp = client.get("/api/v1/export/signed/%s" % sid,
                      params={"signer": signer})
    assert resp.status_code == 200
    assert resp.headers["content-type"] == "application/zip"
    return resp.content


def test_signed_zip_contents():
    client = _client()
    sid = _session(client)
    content = _signed_zip(client, sid)

    with zipfile.ZipFile(io.BytesIO(content)) as zf:
        names = zf.namelist()
        assert "manifest.json" in names
        assert "manifest.sig" in names
        assert "graph_2026-11.csv" in names
        assert "graph_2026-11.xls" in names
        assert "tabel_T13_2026-11.html" in names
        assert "tabel_OKUD0504421_2026-11.html" in names
        assert "graph_podpis_2026-11.html" in names

        manifest = json.loads(zf.read("manifest.json").decode("utf-8"))
        assert manifest["signer"] == "Зав. УПО"
        assert manifest["year"] == 2026 and manifest["month"] == 11
        assert manifest["algorithm"] == "HMAC-SHA256"
        assert len(manifest["files"]) == 5
        for f in manifest["files"]:
            assert f["size"] == len(zf.read(f["name"]))
            assert len(f["sha256"]) == 64

        # подпись манифеста сходится
        manifest_bytes = zf.read("manifest.json")
        manifest_sig = zf.read("manifest.sig").decode("utf-8")
        assert signing.verify_bytes(manifest_bytes, manifest_sig) is True


def test_verify_endpoint_ok():
    client = _client()
    sid = _session(client)
    content = _signed_zip(client, sid)

    resp = client.post("/api/v1/export/verify",
                       files={"file": ("pkg.zip", io.BytesIO(content),
                                       "application/zip")})
    assert resp.status_code == 200
    report = resp.json()
    assert report["ok"] is True
    assert report["errors"] == []
    assert len(report["files"]) == 5
    assert all(f["ok"] for f in report["files"])
    assert report["signer"] == "Зав. УПО"


def test_verify_endpoint_tampered():
    """Подменённый файл внутри пакета не проходит проверку."""
    client = _client()
    sid = _session(client)
    content = _signed_zip(client, sid)

    # перепаковываем с изменённым CSV (манифест остаётся старым)
    buf = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(content)) as src, \
            zipfile.ZipFile(buf, "w") as dst:
        for name in src.namelist():
            data = src.read(name)
            if name == "graph_2026-11.csv":
                data = data.replace(b"8-15,48", b"9-15,48")
            dst.writestr(name, data)

    resp = client.post("/api/v1/export/verify",
                       files={"file": ("pkg.zip", io.BytesIO(buf.getvalue()),
                                       "application/zip")})
    assert resp.status_code == 200
    report = resp.json()
    assert report["ok"] is False
    assert any("csv" in e for e in report["errors"])


